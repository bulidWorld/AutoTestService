#!/usr/bin/env python3
"""Synchronize PostgreSQL schema from db/*.xml.

Requires psycopg (v3) or psycopg2. Existing objects are safe because the XML
statements are idempotent; a checksum ledger prevents rerunning unchanged SQL.
"""
from __future__ import annotations
import argparse, hashlib, re, sys
from pathlib import Path
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DIR = ROOT / "db"

def qident(value: str) -> str:
    return '"' + value.replace('"', '""') + '"'

def load_statements(directory: Path):
    """Create tables first, then guarded foreign keys, then custom SQL."""
    foreign_keys = []
    raw_statements = []
    for path in sorted(directory.glob("*.xml")):
        root = ET.parse(path).getroot()
        if root.tag != "database":
            raise ValueError(f"{path}: root element must be <database>")
        def q(name):
            return qident(name)
        def cols(value):
            return ', '.join(q(x.strip().strip('"')) for x in value.split(','))
        for ext in root.findall("./extensions/extension"):
            name = ext.attrib["name"]
            yield f"{path.stem}-extension-{name}", f"CREATE EXTENSION IF NOT EXISTS {q(name)}"
        for table in root.findall("./tables/table"):
            tn = q(table.attrib["name"])
            parts = []
            for col in table.findall("./columns/column"):
                item = f"{q(col.attrib['name'])} {col.attrib['type']}"
                if col.attrib.get("collation"): item += f" COLLATE {col.attrib['collation']}"
                if col.attrib.get("identity", "false").lower() == "true": item += " GENERATED BY DEFAULT AS IDENTITY"
                if col.attrib.get("default"): item += f" DEFAULT {col.attrib['default']}"
                if col.attrib.get("nullable", "true").lower() == "false": item += " NOT NULL"
                parts.append(item)
            for node in table.findall("./constraints/*"):
                tag = node.tag
                if tag in ("primary-key", "unique"):
                    kind = "PRIMARY KEY" if tag == "primary-key" else "UNIQUE"
                    parts.append(f"CONSTRAINT {q(node.attrib['name'])} {kind} ({cols(node.attrib['columns'])})")
                elif tag == "check":
                    parts.append(f"CONSTRAINT {q(node.attrib['name'])} CHECK ({node.attrib['expression']})")
                elif tag == "foreign-key":
                    item = (f"CONSTRAINT {q(node.attrib['name'])} FOREIGN KEY ({cols(node.attrib['columns'])}) "
                            f"REFERENCES {q(node.attrib['references-table'])} ({cols(node.attrib['references-columns'])})")
                    if node.attrib.get("on-delete", "NO ACTION") != "NO ACTION": item += f" ON DELETE {node.attrib['on-delete']}"
                    if node.attrib.get("on-update", "NO ACTION") != "NO ACTION": item += f" ON UPDATE {node.attrib['on-update']}"
                    sql = (
                        "DO $$\nBEGIN\n    IF NOT EXISTS (\n"
                        "        SELECT 1 FROM pg_constraint\n"
                        f"        WHERE conname = {quote_literal(node.attrib['name'])}\n"
                        f"          AND conrelid = {quote_literal(tn)}::regclass\n"
                        "    ) THEN\n"
                        f"        ALTER TABLE {tn} ADD {item};\n"
                        "    END IF;\nEND $$"
                    )
                    foreign_keys.append((
                        f"{path.stem}-foreign-key-{table.attrib['name']}-{node.attrib['name']}", sql
                    ))
            ine = " IF NOT EXISTS" if table.attrib.get("if-not-exists", "true").lower() == "true" else ""
            partition = table.find("./partition-by")
            partition_sql = ""
            if partition is not None:
                partition_sql = f" PARTITION BY {partition.attrib['method']} ({cols(partition.attrib['columns'])})"
            yield f"{path.stem}-table-{table.attrib['name']}", f"CREATE TABLE{ine} {tn} (\n    " + ",\n    ".join(parts) + "\n)" + partition_sql
            if table.attrib.get("comment"):
                yield f"{path.stem}-comment-table-{table.attrib['name']}", f"COMMENT ON TABLE {tn} IS {quote_literal(table.attrib['comment'])}"
            for col in table.findall("./columns/column"):
                if col.attrib.get("comment"):
                    yield f"{path.stem}-comment-column-{table.attrib['name']}-{col.attrib['name']}", f"COMMENT ON COLUMN {tn}.{q(col.attrib['name'])} IS {quote_literal(col.attrib['comment'])}"
            for index in table.findall("./indexes/index"):
                unique = "UNIQUE " if index.attrib.get("unique", "false").lower() == "true" else ""
                ine = " IF NOT EXISTS" if index.attrib.get("if-not-exists", "true").lower() == "true" else ""
                ixcols = ', '.join(q(c.attrib['name']) + (f" {c.attrib['order']}" if c.attrib.get('order', 'ASC') != 'ASC' else '') for c in index.findall("column"))
                sql = f"CREATE {unique}INDEX{ine} {q(index.attrib['name'])} ON {tn} USING {index.attrib.get('method', 'btree')} ({ixcols})"
                if index.attrib.get("where"): sql += f" WHERE {index.attrib['where']}"
                yield f"{path.stem}-index-{index.attrib['name']}", sql
                if index.attrib.get("comment"):
                    yield f"{path.stem}-comment-index-{index.attrib['name']}", f"COMMENT ON INDEX {q(index.attrib['name'])} IS {quote_literal(index.attrib['comment'])}"
        for node in root.findall("./statements/statement"):
            ident, sql = node.attrib.get("id"), (node.findtext("sql") or "").strip()
            if not ident or not sql: raise ValueError(f"{path}: statement requires id and sql")
            raw_statements.append((ident, sql))
    yield from foreign_keys
    yield from raw_statements

def load_table_definitions(directory: Path):
    """Return managed table names and their XML column definitions."""
    result = {}
    for path in sorted(directory.glob("*.xml")):
        root = ET.parse(path).getroot()
        for table in root.findall("./tables/table"):
            result[table.attrib["name"].strip('"')] = {
                col.attrib["name"].strip('"'): col.attrib
                for col in table.findall("./columns/column")
            }
    return result

def quote_literal(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"

def connect():
    from app.repository.database import connect as configured_connect
    return configured_connect()

def main():
    ap = argparse.ArgumentParser(description="Generate and execute SQL from XML schema definitions")
    ap.add_argument("--dir", type=Path, default=DEFAULT_DIR)
    ap.add_argument("--dry-run", action="store_true", help="print pending SQL without executing")
    ap.add_argument("--sql-out", type=Path, help="write generated pending SQL to this file")
    args = ap.parse_args()
    from lxml import etree
    from app.config.logging import configure_logging
    from app.config.settings import load_settings
    settings = load_settings()
    configure_logging(settings)
    validator = etree.XMLSchema(etree.parse(str(ROOT / "db/database.xsd")))
    xml_files = sorted(args.dir.glob("*.xml"))
    if not xml_files:
        raise ValueError("数据库 XML 目录为空")
    for path in xml_files:
        validator.assertValid(etree.parse(str(path)))
    statements = list(load_statements(args.dir))
    table_definitions = load_table_definitions(args.dir)
    conn = connect()
    try:
        cur = conn.cursor()
        if not args.dry_run:
            cur.execute("""CREATE TABLE IF NOT EXISTS schema_xml_migration (
                statement_id varchar(200) PRIMARY KEY,
                checksum varchar(64) NOT NULL,
                applied_at timestamptz NOT NULL DEFAULT now()
            )""")
            conn.commit()
        cur.execute("SELECT to_regclass('schema_xml_migration')")
        if cur.fetchone()[0] is not None:
            cur.execute("SELECT statement_id, checksum FROM schema_xml_migration")
            applied = dict(cur.fetchall())
        else:
            applied = {}
        pending = [(i, s) for i, s in statements if applied.get(i) != hashlib.sha256(s.encode()).hexdigest()]
        expected_tables = {
            m.group(1).strip('"') for _, s in statements
            for m in [re.search(r"CREATE TABLE IF NOT EXISTS\s+(?:public\.)?(\"?[A-Za-z_][A-Za-z0-9_]*\"?)", s, re.I)]
            if m
        }
        cur.execute("SELECT tablename FROM pg_catalog.pg_tables WHERE schemaname = current_schema()")
        existing_tables = {row[0] for row in cur.fetchall()}
        missing_tables = sorted(expected_tables - existing_tables)
        pending_ids = {ident for ident, _ in pending}
        for table_name in missing_tables:
            for ident, sql in statements:
                if (re.search(r"CREATE TABLE(?: IF NOT EXISTS)?\s+\"?" + re.escape(table_name) + r"\"?\b", sql, re.I)
                        and ident not in pending_ids):
                    pending.append((ident, sql))
                    pending_ids.add(ident)
                    break
        # Detect column additions/removals independently of the statement ledger.
        cur.execute("""SELECT table_name, column_name
                       FROM information_schema.columns
                       WHERE table_schema = current_schema()""")
        actual_columns = {}
        for table_name, column_name in cur.fetchall():
            actual_columns.setdefault(table_name, set()).add(column_name)
        for table_name, columns in table_definitions.items():
            if table_name not in existing_tables:
                continue
            expected_columns = set(columns)
            for column_name, definition in columns.items():
                if column_name in actual_columns.get(table_name, set()):
                    continue
                item = f'ALTER TABLE {qident(table_name)} ADD COLUMN {qident(column_name)} {definition["type"]}'
                if definition.get("collation"): item += f' COLLATE {definition["collation"]}'
                if definition.get("identity", "false").lower() == "true": item += " GENERATED BY DEFAULT AS IDENTITY"
                if definition.get("default"): item += f' DEFAULT {definition["default"]}'
                if definition.get("nullable", "true").lower() == "false": item += " NOT NULL"
                pending.append((f"column-add-{table_name}-{column_name}", item))
            # Existing columns are intentionally retained. XML synchronization
            # only adds missing columns and never deletes user/data columns.
        # Reinsert restored tables in declaration order and add missing columns
        # before column comments, foreign keys or other dependent statements.
        pending_by_id = dict(pending)
        column_additions = [(i, s) for i, s in pending if i.startswith("column-add-")]
        ordered = []
        additions_inserted = False
        raw_statement_ids = {
            node.attrib["id"]
            for path in args.dir.glob("*.xml")
            for node in ET.parse(path).getroot().findall("./statements/statement")
        }
        for ident, sql in statements:
            if "-comment-column-" in ident or "-foreign-key-" in ident or ident in raw_statement_ids:
                if not additions_inserted:
                    ordered.extend(column_additions)
                    additions_inserted = True
            if ident in pending_by_id:
                ordered.append((ident, pending_by_id[ident]))
        if not additions_inserted:
            ordered.extend(column_additions)
        pending = ordered
        generated = "\n\n".join(f"-- {i}\n{s};" for i, s in pending) + ("\n" if pending else "")
        if args.sql_out:
            args.sql_out.write_text(generated, encoding="utf-8")
        print(f"XML statements: {len(statements)}, pending: {len(pending)}")
        print(f"Tables: {len(existing_tables & expected_tables)}/{len(expected_tables)} defined tables present"
              + (f"; missing: {', '.join(missing_tables)}" if missing_tables else ""))
        if args.dry_run:
            print(generated, end="")
            return
        cur.execute("""CREATE TABLE IF NOT EXISTS database_change_log (
            id bigserial PRIMARY KEY,
            version bigint NOT NULL,
            statement_id varchar(200) NOT NULL,
            sql_text text NOT NULL,
            checksum varchar(64) NOT NULL,
            status varchar(16) NOT NULL,
            error_message text,
            created_at timestamptz NOT NULL DEFAULT now(),
            executed_at timestamptz,
            CONSTRAINT ck_database_change_log_status
                CHECK (status IN ('pending', 'applied', 'failed'))
        )""")
        # Upgrade installations that created the audit table before versioning.
        cur.execute("""ALTER TABLE database_change_log
            ADD COLUMN IF NOT EXISTS version bigint NOT NULL DEFAULT 0""")
        cur.execute("CREATE SEQUENCE IF NOT EXISTS database_change_log_version_seq START WITH 1")
        cur.execute("""SELECT COALESCE((SELECT MAX(version) FROM database_change_log), 0),
                              last_value
                       FROM database_change_log_version_seq""")
        max_version, sequence_value = cur.fetchone()
        if max_version > sequence_value:
            cur.execute("SELECT setval('database_change_log_version_seq', %s, true)", (max_version,))
        conn.commit()
        cur.execute("SELECT nextval('database_change_log_version_seq')")
        execution_version = cur.fetchone()[0]
        conn.commit()
        print(f"Execution version: {execution_version}")
        for ident, sql in pending:
            checksum = hashlib.sha256(sql.encode()).hexdigest()
            # Commit the audit record before executing the DDL so it remains
            # available even when the DDL fails and is rolled back.
            cur.execute("""INSERT INTO database_change_log
                (version, statement_id, sql_text, checksum, status)
                VALUES (%s, %s, %s, %s, 'pending')
                RETURNING id""", (execution_version, ident, sql, checksum))
            change_id = cur.fetchone()[0]
            conn.commit()
            try:
                cur.execute(sql)
                cur.execute("""INSERT INTO schema_xml_migration(statement_id, checksum)
                    VALUES (%s, %s) ON CONFLICT (statement_id) DO UPDATE
                    SET checksum = EXCLUDED.checksum, applied_at = now()""",
                    (ident, checksum))
                cur.execute("""UPDATE database_change_log
                    SET status = 'applied', executed_at = now()
                    WHERE id = %s""", (change_id,))
                conn.commit()
            except Exception as exc:
                conn.rollback()
                cur.execute("""UPDATE database_change_log
                    SET status = 'failed', error_message = %s
                    WHERE id = %s""", (str(exc), change_id))
                conn.commit()
                raise
        print("Schema synchronization completed.")
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()

if __name__ == "__main__":
    sys.path.insert(0, str(ROOT))
    import logging
    from app.config.logging import configure_bootstrap_logging
    configure_bootstrap_logging()
    try:
        main()
    except Exception as exc:
        logging.getLogger(__name__).exception("数据库 XML 同步失败")
        print(f"数据库同步失败 ({type(exc).__name__})，请检查配置、XML 和 error.log", file=sys.stderr)
        sys.exit(1)
